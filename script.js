// Override safeText to work even if element has children (for buttons with spans etc.)
function safeText(id, text) {
  const el = document.getElementById(id);
  if (!el || text === undefined) return;
  // Only replace if no complex child structure (just text or single span)
  if (el.children.length === 0) {
    el.textContent = text;
  } else if (el.children.length === 1 && el.children[0].tagName === 'SPAN') {
    // keep the span, just update text node before it
    const tn = Array.from(el.childNodes).find(n => n.nodeType === 3);
    if (tn) tn.textContent = text;
  }
}

function safePlaceholder(id, text) {
  const el = document.getElementById(id);
  if (el) el.placeholder = text;
}

